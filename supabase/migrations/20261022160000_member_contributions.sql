CREATE TABLE IF NOT EXISTS public.member_contributions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_account_no text NOT NULL,
    phone text NOT NULL,
    mpesa_reference text NOT NULL UNIQUE,
    amount numeric(10, 2) NOT NULL DEFAULT 200 CHECK (amount = 200),
    status text NOT NULL DEFAULT 'Pending Verification'
        CHECK (status IN ('Pending Verification', 'Verified', 'Rejected')),
    submitted_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.member_contributions ENABLE ROW LEVEL SECURITY;
